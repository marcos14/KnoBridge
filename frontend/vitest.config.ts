import { defineConfig, mergeConfig } from "vitest/config";

import viteConfig from "./vite.config.ts";

export default mergeConfig(
  viteConfig,
  defineConfig({
    test: {
      environment: "jsdom",
      setupFiles: ["./src/test/setup.ts"],
      // Unit and component tests live next to the code; e2e/ belongs to Playwright.
      include: ["src/**/*.test.{ts,tsx}"],
      // Half the cores, not one worker per core: every worker runs jsdom with coverage, and with
      // all cores busy the CPU starvation made unrelated findBy waits time out at random (seen in
      // plans 0005 and 0008). Fewer workers keep the suite deterministic at a similar wall time.
      maxWorkers: "50%",
      coverage: {
        // Always on, like --cov in the backend: "pnpm test -- --coverage" forwards a literal "--" that
        // vitest ignores, so the gate cannot depend on the flag. test:watch turns it off.
        enabled: true,
        provider: "v8",
        // All source code under src/; the AGENTS.md files there are docs and cannot be parsed as JS.
        include: ["src/**/*.{ts,tsx}"],
        exclude: [
          // DOM bootstrap only: it calls createRoot on the real #root element of index.html, which
          // does not exist under jsdom. Everything it renders (<App />) is covered by App.test.tsx.
          "src/main.tsx",
          "src/**/*.d.ts",
          // Test infrastructure (setup and helpers), not product code.
          "src/test/**",
          // Generated by openapi-typescript from docs/specs/openapi.json (pnpm gen:api); types only.
          "src/lib/api/schema.gen.ts",
          // shadcn/ui components copied by the shadcn CLI: third-party code kept close to upstream,
          // exercised through our own components (e.g. ApiStatus), not tested on its own.
          "src/components/ui/**",
        ],
        thresholds: {
          lines: 95,
          branches: 95,
          functions: 95,
          statements: 95,
        },
      },
    },
  }),
);
