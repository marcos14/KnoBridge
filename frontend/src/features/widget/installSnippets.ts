import type { WidgetMode } from "@/lib/api/widgets";

/**
 * Copyable snippets of the widget (`docs/specs/widget.md`, "Embutir o elemento" and "Identidade
 * assinada"). The signing secret is never in them: the host's server reads it from this variable.
 */
export const SIGNING_SECRET_VARIABLE = "KNOBRIDGE_WIDGET_SIGNING_SECRET";

/** Where the instance serves the widget: one stable file, `/widget/v1/knobridge-chat.js`. */
export function widgetScriptUrl(serverUrl: string): string {
  return `${serverUrl.replace(/\/+$/, "")}/widget/v1/knobridge-chat.js`;
}

/** Height the inline example gives the element (the host decides it; minimum 360 px). */
export const INLINE_EXAMPLE_HEIGHT = "600px";

/** The `<script>` and the element, for the widget's mode (the inline one with a height). */
export function installSnippet(serverUrl: string, publicKey: string, mode: WidgetMode): string {
  const script = `<script src="${widgetScriptUrl(serverUrl)}" defer></script>`;
  const element =
    mode === "inline"
      ? `<knobridge-chat widget-key="${publicKey}" mode="inline" style="height: ${INLINE_EXAMPLE_HEIGHT}"></knobridge-chat>`
      : `<knobridge-chat widget-key="${publicKey}"></knobridge-chat>`;
  return `${script}\n${element}`;
}

/** The element with the signed identity the host's server writes into each page. */
export function identityElementSnippet(publicKey: string): string {
  return [
    "<!-- identity: generated by your server on every page load (see the functions below) -->",
    `<knobridge-chat widget-key="${publicKey}" identity="{{ knobridge_identity }}"></knobridge-chat>`,
  ].join("\n");
}

/** Python on the host's server: signs `v1.<payload>.<HMAC-SHA256 hex>` with the `kbs_` secret. */
export function identityPythonSnippet(): string {
  return [
    "import base64, hashlib, hmac, json, os, time",
    "",
    "def knobridge_identity(sub: str, name: str | None, email: str | None, ttl: int = 3600) -> str:",
    "    now = int(time.time())",
    '    claims = {"sub": sub, "name": name, "email": email, "iat": now, "exp": now + ttl}',
    "    claims = {k: v for k, v in claims.items() if v is not None}",
    '    raw = json.dumps(claims, separators=(",", ":"), ensure_ascii=False).encode()',
    '    payload = base64.urlsafe_b64encode(raw).rstrip(b"=").decode()',
    `    key = os.environ["${SIGNING_SECRET_VARIABLE}"].encode()  # kbs_…`,
    '    signature = hmac.new(key, f"v1.{payload}".encode(), hashlib.sha256).hexdigest()',
    '    return f"v1.{payload}.{signature}"',
  ].join("\n");
}

/** Node on the host's server, the same signature as the Python one. */
export function identityNodeSnippet(): string {
  return [
    'import { createHmac } from "node:crypto";',
    "",
    "export function knobridgeIdentity({ sub, name, email }, ttl = 3600) {",
    "  const iat = Math.floor(Date.now() / 1000);",
    '  const payload = Buffer.from(JSON.stringify({ sub, name, email, iat, exp: iat + ttl })).toString("base64url");',
    `  const signature = createHmac("sha256", process.env.${SIGNING_SECRET_VARIABLE}).update(\`v1.\${payload}\`).digest("hex");`,
    "  return `v1.${payload}.${signature}`;",
    "}",
  ].join("\n");
}
