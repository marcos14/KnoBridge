import type { TFunction } from "i18next";
import { useState } from "react";
import { useTranslation } from "react-i18next";

import { CopyButton } from "@/components/CopyButton";
import { FormAlert } from "@/components/FormAlert";
import { type TestOutcome, TestResult } from "@/components/TestResult";
import { Button } from "@/components/ui/button";
import {
  type Product,
  type TicketWebhookSecret,
  type TicketWebhookTest,
  useRotateTicketWebhookSecret,
  useTestTicketWebhook,
} from "@/lib/api/products";
import { formatDateTime } from "@/lib/intl";

import { webhookApiErrorText, webhookErrorText } from "./ticketWebhook";

interface TicketWebhookPanelProps {
  workspaceId: string;
  product: Product;
  canManageSecret: boolean;
}

/**
 * The saved webhook of a product: its signing secret (generated by owners and admins, shown
 * once; it only lives in this component, which unmounts with the dialog) and "Testar entrega",
 * one signed test event to the saved URL with what the destination answered.
 */
export function TicketWebhookPanel({
  workspaceId,
  product,
  canManageSecret,
}: TicketWebhookPanelProps) {
  const { t, i18n } = useTranslation();
  const createdAt = product.ticket_webhook_secret_created_at;

  return (
    <section
      aria-labelledby="ticket-webhook-secret-title"
      className="flex flex-col gap-3 rounded-md border px-3 py-3"
    >
      <h3 id="ticket-webhook-secret-title" className="text-sm font-medium">
        {t("products.webhook.secretTitle")}
      </h3>
      <p className="text-muted-foreground text-sm">{t("products.webhook.secretDescription")}</p>
      <p className="text-sm">
        {createdAt === null
          ? t("products.webhook.noSecret")
          : t("products.webhook.secretCreated", {
              date: formatDateTime(new Date(createdAt), i18n.language),
            })}
      </p>
      {canManageSecret ? (
        <SecretControls
          workspaceId={workspaceId}
          productId={product.id}
          replacing={createdAt !== null}
        />
      ) : (
        <p className="text-sm">{t("products.webhook.secretManagersOnly")}</p>
      )}
      <TestDelivery
        workspaceId={workspaceId}
        productId={product.id}
        configured={product.ticket_webhook_configured}
      />
    </section>
  );
}

interface SecretControlsProps {
  workspaceId: string;
  productId: string;
  /** There is a secret already: generating another one asks for confirmation first. */
  replacing: boolean;
}

function SecretControls({ workspaceId, productId, replacing }: SecretControlsProps) {
  const { t } = useTranslation();
  const [confirming, setConfirming] = useState(false);
  const [issued, setIssued] = useState<TicketWebhookSecret | null>(null);
  const rotate = useRotateTicketWebhookSecret(workspaceId);

  function generate() {
    setConfirming(false);
    setIssued(null);
    rotate.mutate(productId, { onSuccess: setIssued });
  }

  if (issued !== null) {
    return (
      <div className="flex flex-col gap-2">
        <p className="text-sm">{t("products.webhook.secretIssued")}</p>
        <code
          aria-label={t("products.webhook.secretLabel")}
          className="bg-muted rounded-md p-2 text-sm break-all"
        >
          {issued.secret}
        </code>
        <CopyButton text={issued.secret} label={t("products.webhook.copySecret")} />
      </div>
    );
  }

  return (
    <div className="flex flex-col gap-2">
      {rotate.isError && <FormAlert message={webhookApiErrorText(rotate.error, t)} />}
      {confirming ? (
        <div className="flex flex-col gap-2 rounded-md border border-amber-500/50 px-3 py-2">
          <p className="text-sm">{t("products.webhook.replaceWarning")}</p>
          <div className="flex flex-wrap gap-2">
            <Button type="button" size="sm" onClick={generate}>
              {t("products.webhook.replaceConfirm")}
            </Button>
            <Button
              type="button"
              size="sm"
              variant="outline"
              onClick={() => {
                setConfirming(false);
              }}
            >
              {t("products.webhook.replaceCancel")}
            </Button>
          </div>
        </div>
      ) : (
        <Button
          type="button"
          variant="outline"
          size="sm"
          className="w-fit"
          disabled={rotate.isPending}
          onClick={() => {
            if (replacing) {
              setConfirming(true);
            } else {
              generate();
            }
          }}
        >
          {rotate.isPending
            ? t("products.webhook.generating")
            : replacing
              ? t("products.webhook.replaceSecret")
              : t("products.webhook.generateSecret")}
        </Button>
      )}
    </div>
  );
}

interface TestDeliveryProps {
  workspaceId: string;
  productId: string;
  /** URL and secret saved: only then there is something to test. */
  configured: boolean;
}

function TestDelivery({ workspaceId, productId, configured }: TestDeliveryProps) {
  const { t } = useTranslation();
  const test = useTestTicketWebhook(workspaceId);

  return (
    <div className="flex flex-col gap-2">
      <div className="flex flex-wrap items-center gap-2">
        <Button
          type="button"
          variant="outline"
          size="sm"
          disabled={!configured || test.isPending}
          onClick={() => {
            test.mutate(productId);
          }}
        >
          {test.isPending ? t("products.webhook.testing") : t("products.webhook.test")}
        </Button>
        <span className="text-muted-foreground text-xs">
          {configured ? t("products.webhook.testHint") : t("products.webhook.notConfigured")}
        </span>
      </div>
      {/* A new test is pending, not settled: the previous result goes away when it starts. */}
      {test.isError && (
        <TestResult outcome={{ ok: false, message: webhookApiErrorText(test.error, t) }} />
      )}
      {test.isSuccess && (
        <>
          <TestResult outcome={deliveryOutcome(test.data, t)} />
          <p className="text-muted-foreground text-xs">
            {t("products.webhook.deliveryId", { id: test.data.delivery_id })}
          </p>
        </>
      )}
    </div>
  );
}

function deliveryOutcome(result: TicketWebhookTest, t: TFunction): TestOutcome {
  if (result.ok || result.error === null) {
    return { ok: true, message: t("products.webhook.testOk") };
  }
  return {
    ok: false,
    message: t("products.webhook.testFailed", {
      reason: webhookErrorText(result.error.code, result.error.details, t),
    }),
  };
}
