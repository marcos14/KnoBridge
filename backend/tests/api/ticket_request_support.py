"""Helpers for the ticket request API tests: an assistant whose webhook is configured (URL saved
through a fake resolver, secret generated by the API), a "no source" answer to ask about, the
fake delivery starter and direct reads of the stored requests.

Not a test module; imported by its basename.
"""

from __future__ import annotations

import uuid
from dataclasses import dataclass
from typing import cast

import httpx2
from api_support import ApiEnv, SessionFactory, run_db
from chat_support import World, ask, build_world, conversations_path, events, start
from fastapi import FastAPI
from sqlalchemy import select, update

from fakes.ticket_webhook_starter import FakeTicketWebhookStarter
from knobridge.api.ticket_requests import get_ticket_webhook_starter
from knobridge.api.ticket_webhook import get_outbound_resolver
from knobridge.conversations.models import Message, MessageStatus
from knobridge.core.db import system_session
from knobridge.tenancy.models import Role
from knobridge.tickets.models import TicketRequest

HOOK_HOST = "hooks.example.com"
HOOK_URL = f"https://{HOOK_HOST}/knobridge"
PUBLIC_IP = "93.184.216.34"
QUESTION = "Como emito nota fiscal para cliente do exterior?"


class FakeResolver:
    async def resolve(self, host: str, port: int) -> list[str]:
        if host != HOOK_HOST:
            raise OSError("does not resolve")
        return [PUBLIC_IP]


class RequestOverrides:
    """The resolver used when saving the webhook URL and the fake delivery starter."""

    def __init__(self, app: FastAPI) -> None:
        self.app = app
        self.starter = FakeTicketWebhookStarter()
        app.dependency_overrides[get_outbound_resolver] = FakeResolver
        app.dependency_overrides[get_ticket_webhook_starter] = lambda: self.starter

    def clear(self) -> None:
        self.app.dependency_overrides.pop(get_outbound_resolver, None)
        self.app.dependency_overrides.pop(get_ticket_webhook_starter, None)


def install(api: ApiEnv) -> RequestOverrides:
    return RequestOverrides(cast(FastAPI, api.client.app))


@dataclass(frozen=True)
class Asked:
    world: World
    conversation_id: str
    question_id: str
    answer_id: str
    # The ``done`` event of the answer.
    done: dict[str, object]


def configured_world(api: ApiEnv, *roles: Role, webhook: bool = True) -> World:
    """A workspace whose first user (owner or admin) has an assistant with a configured
    webhook (or none, with ``webhook=False``); that user stays logged in."""
    extra: dict[str, object] = {"ticket_webhook_url": HOOK_URL} if webhook else {}
    world = build_world(api, *(roles or (Role.OWNER,)), **extra)
    if webhook:
        secret = api.client.post(
            f"/v1/workspaces/{world.workspace_id}/assistants/{world.assistant_id}"
            "/ticket-webhook/secret",
            headers=api.csrf_headers(),
        )
        assert secret.status_code == 201, secret.text
    return world


def ask_question(api: ApiEnv, world: World, question: str = QUESTION) -> Asked:
    """A new conversation of the logged-in user with one question and its answer."""
    conversation_id = start(api, world)
    sent = events(ask(api, world.workspace_id, conversation_id, question))
    citations, done = sent[0][1], sent[-1][1]
    return Asked(
        world,
        conversation_id,
        str(citations["user_message_id"]),
        str(citations["message_id"]),
        done,
    )


def requests_path(asked: Asked, suffix: str = "") -> str:
    base = conversations_path(asked.world.workspace_id, asked.conversation_id)
    return f"{base}/ticket-requests{suffix}"


def preview(api: ApiEnv, asked: Asked, message_id: str | None = None) -> httpx2.Response:
    return api.client.post(
        requests_path(asked, "/preview"),
        json={"message_id": message_id or asked.answer_id},
        headers=api.csrf_headers(),
    )


def create(
    api: ApiEnv, asked: Asked, summary: str = "Resumo do pedido.", message_id: str | None = None
) -> httpx2.Response:
    return api.client.post(
        requests_path(asked),
        json={"message_id": message_id or asked.answer_id, "summary": summary},
        headers=api.csrf_headers(),
    )


def stored_requests(api: ApiEnv, workspace_id: uuid.UUID) -> list[TicketRequest]:
    async def scenario(factory: SessionFactory) -> list[TicketRequest]:
        async with system_session(factory) as db:
            return list(
                await db.scalars(
                    select(TicketRequest).where(TicketRequest.workspace_id == workspace_id)
                )
            )

    return run_db(api.database_url, scenario)


def set_message_status(api: ApiEnv, message_id: str, status: MessageStatus) -> None:
    update_message(api, message_id, status=status)


def update_message(api: ApiEnv, message_id: str, **values: object) -> None:
    async def scenario(factory: SessionFactory) -> None:
        async with system_session(factory) as db:
            await db.execute(
                update(Message).where(Message.id == uuid.UUID(message_id)).values(**values)
            )

    run_db(api.database_url, scenario)
