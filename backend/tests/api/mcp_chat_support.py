"""Helpers for the ``ask`` and ``open_ticket`` tests of the MCP server: a world whose levels
answer with a priced model, a scripted LLM and the product's ticket webhook configured through
the panel (URL saved through a fake resolver, secret generated by the API).

Not a test module; imported by its basename.
"""

from __future__ import annotations

import uuid
from dataclasses import dataclass

from api_support import ApiEnv
from mcp_support import McpWorld, add_product, mcp_world
from product_support import seed_level
from search_support import Passage
from ticket_request_support import HOOK_URL, install

from fakes.llm_provider import RecordingFactory, ScriptedLLMProvider
from knobridge.levels.level import ResponseLevel

# Priced in the default table: 42 input and 7 output tokens of the scripted provider.
MODEL = "gpt-4.1-mini"
COST = 0.000028
QUESTION = "Como fecho o caixa com o relatório Z?"


@dataclass(frozen=True)
class AskWorld:
    mcp: McpWorld
    # A product of the same workspace without collections: every answer is ``no_source``.
    empty_product: str

    @property
    def workspace_id(self) -> uuid.UUID:
        return self.mcp.workspace_id

    @property
    def product_id(self) -> str:
        return self.mcp.product_id


def ask_world(api: ApiEnv, *passages: Passage, configured: bool = True) -> AskWorld:
    """``mcp_world`` with every level answering with ``MODEL`` (or none, ``configured=False``)
    and a product without collections. The owner stays logged in."""
    world = mcp_world(api, *passages)
    if configured:
        for level in ResponseLevel:
            seed_level(
                api, world.workspace_id, str(world.search.provider_id), level=level, model=MODEL
            )
    return AskWorld(world, add_product(api, world, "Vazio", collections=False))


def scripted(provider: ScriptedLLMProvider | None = None) -> RecordingFactory:
    return RecordingFactory(provider or ScriptedLLMProvider())


def ask_args(product: str, **arguments: object) -> tuple[str, dict[str, object]]:
    return "ask", {"product": product, "question": QUESTION, **arguments}


def configure_webhook(api: ApiEnv, workspace_id: uuid.UUID, product_id: str) -> None:
    """The product's webhook URL and secret, saved through the panel by the logged-in owner."""
    overrides = install(api)
    try:
        path = f"/v1/workspaces/{workspace_id}/products/{product_id}"
        saved = api.client.patch(
            path, json={"ticket_webhook_url": HOOK_URL}, headers=api.csrf_headers()
        )
        assert saved.status_code == 200, saved.text
        secret = api.client.post(f"{path}/ticket-webhook/secret", headers=api.csrf_headers())
        assert secret.status_code == 201, secret.text
    finally:
        overrides.clear()
